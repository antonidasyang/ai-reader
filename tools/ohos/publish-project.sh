#!/usr/bin/env bash
# Publish the DevEco project that build.sh generated (build-ohos/harmonyos-build)
# to the `harmonyos-project` branch, so a HarmonyOS PC can `git pull` it and
# open it straight in DevEco Studio — no zip to copy around.
#
#   tools/ohos/build.sh && tools/ohos/publish-project.sh
#
# The branch holds build output only (prebuilt .so files, ~50 MB compressed
# for the first commit, a few MB per update) and has its own history,
# unrelated to main, so main stays free of binaries. It is regenerated from
# scratch each time; never edit it by hand.
set -euo pipefail
source "$(dirname "$0")/env.sh"

BRANCH="${OHOS_PROJECT_BRANCH:-harmonyos-project}"
src="$BUILD_DIR/harmonyos-build"
wt="$BUILD_DIR/project-branch"
[ -f "$src/build-profile.json5" ] || die "no generated project; run tools/ohos/build.sh first"

version=$(sed -nE 's/^project\(ai-reader VERSION ([0-9.]+).*/\1/p' "$AIREADER_ROOT/CMakeLists.txt")
built=$(sed -nE 's/.*"versionName": *"([^"]+)".*/\1/p' "$src/AppScope/app.json5")
[ "$built" = "$version" ] || die "project is $built but the source is $version; rebuild first"
main_rev=$(git -C "$AIREADER_ROOT" rev-parse --short HEAD)
dirty=$(git -C "$AIREADER_ROOT" status --porcelain --untracked-files=no | grep -v '^?? ' || true)
[ -z "$dirty" ] || die "uncommitted changes in the source tree; commit first so the branch can name its commit"

cd "$AIREADER_ROOT"
git fetch -q origin "$BRANCH" 2>/dev/null || true
if [ ! -d "$wt/.git" ] && [ ! -f "$wt/.git" ]; then
    rm -rf "$wt"
    if git rev-parse -q --verify "origin/$BRANCH" >/dev/null; then
        git worktree add -q -B "$BRANCH" "$wt" "origin/$BRANCH"
    else
        git worktree add -q --orphan -b "$BRANCH" "$wt"
    fi
fi
git -C "$wt" rev-parse -q --verify "origin/$BRANCH" >/dev/null \
    && git -C "$wt" reset -q --hard "origin/$BRANCH"

# Mirror the project, minus hvigor/cmake caches and what DevEco writes locally.
rsync -a --delete \
    --exclude .git --exclude .gitignore --exclude 'README*.md' \
    --exclude .hvigor --exclude 'oh_modules' --exclude local.properties \
    --exclude entry/build --exclude entry/.cxx --exclude .idea \
    "$src/" "$wt/"

cat > "$wt/.gitignore" <<'EOF'
# Written by DevEco / hvigor on the machine that opens the project.
.hvigor/
.idea/
oh_modules/
local.properties
entry/build/
entry/.cxx/
EOF

cat > "$wt/README.md" <<EOF
# AI Reader — HarmonyOS PC project (generated)

AI Reader $version, built from main@$main_rev. **Generated by
\`tools/ohos/publish-project.sh\` on the \`main\` branch — don't edit here**; source
changes go to \`main\`, see \`docs/harmonyos.md\` there.

## Open it on a HarmonyOS PC

    git clone -b $BRANCH --single-branch https://github.com/antonidasyang/ai-reader.git ai-reader-ohos

Then in DevEco Studio: File → Open → \`ai-reader-ohos\`; File → Project Structure →
Signing Configs → *Automatically generate signature*; pick this PC as the device; Run.

Auto-signing writes your signing config into \`build-profile.json5\`. Keep it across
updates with

    git update-index --skip-worktree build-profile.json5

and update with \`git pull\`. (If a pull ever complains about that file, run
\`git update-index --no-skip-worktree build-profile.json5\`, \`git stash\`, pull,
\`git stash pop\`.)

The prebuilt libraries include Qt (LGPLv3, https://www.qt.io/licensing) and
QtPdf/PDFium (BSD), built from the sources pinned in \`tools/ohos/\` on \`main\`.
EOF

git -C "$wt" add -A
if git -C "$wt" diff --cached --quiet; then
    echo "harmonyos-project is already at $version (main@$main_rev)"
    exit 0
fi
git -C "$wt" commit -q -m "AI Reader $version for HarmonyOS PC (main@$main_rev)" \
    -m "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"
git -C "$wt" push -q -u origin "$BRANCH"
echo "pushed $BRANCH: AI Reader $version (main@$main_rev)"
